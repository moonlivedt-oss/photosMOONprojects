class HelpDialog(QDialog):
    def __init__(self, win, topic=None):
        super().__init__(win)
        self.setWindowTitle(f"Справка - Библиотека картинок {VERSION}")
        self.setAttribute(Qt.WidgetAttribute.WA_DeleteOnClose)
        self.resize(940, 640)
        self.q = QLineEdit(placeholderText="Найти в справке: метки, фон, выгрузка, Ctrl+K...", objectName="search")
        self.q.setClearButtonEnabled(True)
        self.q.addAction(lib_icon("magnifying-glass"), QLineEdit.ActionPosition.LeadingPosition)
        self.q.textChanged.connect(self.show_topic)
        self.topics = QListWidget()
        self.topics.setFixedWidth(220)
        for title, icon, _rows in TOPICS:
            self.topics.addItem(title)
            self.topics.item(self.topics.count() - 1).setIcon(lib_icon(icon))
        self.topics.currentRowChanged.connect(lambda _r: (self.q.clear(), self.show_topic()))
        self.text = QTextBrowser()
        self.text.setOpenExternalLinks(True)
        body = QHBoxLayout()
        body.addWidget(self.topics)
        body.addWidget(self.text, 1)
        lay = QVBoxLayout(self)
        lay.addWidget(self.q)
        lay.addLayout(body, 1)
        lay.addWidget(
            QLabel(
                "Ошибки окна пишутся в _tools/_errors.log - его можно приложить к сообщению о баге.", objectName="dim"
            )
        )
        names = [t[0] for t in TOPICS]
        self.topics.setCurrentRow(names.index(topic) if topic in names else 0)
        self.q.setFocus()

    def show_topic(self):
        q = self.q.text().strip().lower()
        if q:
            parts = []
            for title, _icon, rows in TOPICS:
                hit = [r for r in rows if q in " ".join(r).lower()]
                if hit:
                    parts.append(self.render(title, hit))
            self.text.setHtml("".join(parts) or f"<p style='color:{C['dim']}'>Ничего не нашлось.</p>")
            return
        i = self.topics.currentRow()
        if i >= 0:
            self.text.setHtml(self.render(TOPICS[i][0], TOPICS[i][2]))

    @staticmethod
    def render(title, rows):
        out = [
            f"<h2 style='margin:4px 0 10px 0'>{html.escape(title)}</h2><table cellspacing=0 cellpadding=6 width='100%'>"
        ]
        for what, how, keys in rows:
            k = (
                (
                    f"<span style='background:{C['bg3']};color:{C['text']};border-radius:6px'>&nbsp;{html.escape(keys)}"
                    "&nbsp;</span>"
                )
                if keys
                else ""
            )
            out.append(
                f"<tr><td width='34%' valign='top'><b>{html.escape(what)}</b></td>"
                f"<td valign='top' style='color:{C['dim']}'>{html.escape(how)}</td>"
                f"<td valign='top' align='right'>{k}</td></tr>"
            )
        return "".join(out) + "</table>"
