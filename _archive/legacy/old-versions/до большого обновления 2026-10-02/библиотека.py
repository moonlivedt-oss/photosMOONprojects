#  Ctrl+Z отменяет последнее сохранение, переименование, перенос или сжатие.
#
#  Работа с картинками (нарезка, сжатие, отпечатки) - в картинки.py.
#  Интерфейс разложен по файлам в папке "окно":
#    общее.py              пути, настройки, фоновые задачи, файлы
#    оформление.py         тёмная тема (QSS)
#    анимации.py           живой фон, вкладки, переходы, свечение кнопок, всплывающие сообщения
#    миниатюры.py          плитки, кэш миниатюр, значки, рисовальщик плиток
#    виджеты.py            дерево разделов, списки плиток, горячие клавиши
#    раскладка.py          заготовки нарезки, метки в имени, имена кусков, запись
#    отпечатки.py          «уже есть», похожие, цвета, дубли
#    входящие.py           вкладка «Входящие»
#    вкладка_библиотеки.py вкладка «Библиотека» и быстрый просмотр
#    сжатие.py, выгрузка.py, дубли.py, вес.py - окна этих действий
#    главное.py            главное окно, отмена, приём файлов, main()
